const std = @import("std");

pub const TitleText = struct {
    text: []const u8,

    pub fn width(self: *const @This()) u16 {
        var it = std.mem.splitScalar(u8, self.text, '\n');
        var max: u16 = 0;
        while (it.next()) |line| {
            max = @max(max, @as(u16, @intCast(line.len)));
        }
        return max;
    }

    pub fn height(self: *const @This()) u16 {
        var it = std.mem.splitScalar(u8, self.text, '\n');
        var count: u16 = 0;
        while (it.next()) |_| {
            count += 1;
        }
        return count;
    }
};

